# ====== 房價所得比軌跡比較：日本 vs 台灣 ======
# 示意數值：依東京圈新建公寓與內政部（台北市）房價所得比的公開量級手動設定，非官方逐年資料

# 日本：東京都 房價所得比（示意值）
japan_years  = [1980, 1983, 1985, 1987, 1989, 1991, 1993,
                1995, 1998, 2000, 2003, 2005, 2008, 2010,
                2013, 2015, 2018, 2020]
japan_ratios = [8.2,  9.1, 10.5, 14.8, 18.4, 16.2, 12.1,
                10.3,  8.5,  7.8,  7.2,  7.5,  8.1,  7.9,
                 8.3,  9.0, 10.2, 10.8]

# 台灣：台北市 房價所得比（示意值，量級參考內政部資料）
tw_years  = [2002, 2004, 2006, 2008, 2010, 2012, 2014,
             2016, 2018, 2019, 2020, 2021, 2022, 2023, 2024]
tw_ratios = [6.1,  6.8,  8.2,  8.9, 10.1, 12.6, 14.1,
             14.8, 13.5, 14.1, 15.2, 16.2, 16.1, 15.8, 16.0]

# 計算泡沫期的關鍵指標
jp_peak = max(japan_ratios)
jp_peak_yr = japan_years[japan_ratios.index(jp_peak)]
jp_trough = min(japan_ratios[japan_ratios.index(jp_peak):])
jp_decline = (jp_peak - jp_trough) / jp_peak * 100

tw_peak = max(tw_ratios)
tw_peak_yr = tw_years[tw_ratios.index(tw_peak)]
tw_current = tw_ratios[-1]

print("=" * 55)
print("   房價所得比軌跡比較：東京 vs 台北")
print("=" * 55)

stages = [
    ("起漲前",      8.2, 1980, 6.1, 2002),
    ("緩慢攀升",   10.5, 1985, 8.2, 2006),
    ("加速膨脹",   14.8, 1987, 12.6, 2012),
    ("頂峰/高原",  18.4, 1989, 16.2, 2021),
    ("峰值後",     16.2, 1991, 16.0, 2024),
]

print(f"\n{'階段':<12} {'東京':>8}  {'年份':>5}  "
      f"{'台北':>8}  {'年份':>5}")
print("-" * 55)
for stage, jp, jp_y, tw, tw_y in stages:
    print(f"{stage:<12} {jp:>8.1f}x  {jp_y:>5}  "
          f"{tw:>8.1f}x  {tw_y:>5}")

print(f"\n[日本] 峰值: {jp_peak:.1f}x ({jp_peak_yr}) → "
      f"谷底: {jp_trough:.1f}x | 跌幅: {jp_decline:.0f}%")
print(f"[台灣] 峰值: {tw_peak:.1f}x ({tw_peak_yr}) → "
      f"目前: {tw_current:.1f}x | 持平")

# 關鍵差異
print(f"\n關鍵對比:")
print(f"  日本泡沫期: {jp_peak_yr-1985}年 (1985→{jp_peak_yr})")
